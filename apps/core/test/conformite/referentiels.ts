/** apps/core/test/conformite/referentiels.ts — matrice de traçabilité : les exigences des référentiels de sécurité (ANSSI, RFC, OpenID, OWASP ASVS 5.0) que le produit satisfait avec le test qui le démontre, et les exigences non applicables avec leur raison ; referentiels.test.ts vérifie que chaque preuve est un test actif. */

export interface Preuve {
  /** Chemin du fichier de test depuis la racine du dépôt. */
  readonly fichier: string;
  /** Sous-chaîne exacte du titre du test (ou de son fichier). */
  readonly titre: string;
}

export interface Exigence {
  readonly referentiel: string;
  readonly id: string;
  /** Citation courte, dans la langue du référentiel. */
  readonly intitule: string;
  readonly applicable: boolean;
  /** Raison d'une exigence non applicable. */
  readonly pourquoi?: string;
  /** Ce que les preuves couvrent quand elles ne couvrent pas tout l'intitulé. */
  readonly portee?: string;
  readonly preuves: readonly Preuve[];
}

const ex = (
  referentiel: string,
  id: string,
  intitule: string,
  applicable: boolean,
  pourquoi: string | null,
  preuves: readonly (readonly [string, string])[],
  portee: string | null = null,
): Exigence => ({
  referentiel,
  id,
  intitule,
  applicable,
  ...(pourquoi === null ? {} : { pourquoi }),
  ...(portee === null ? {} : { portee }),
  ...(portee === null ? {} : { portee }),
  preuves: preuves.map(([fichier, titre]) => ({ fichier, titre })),
});

