/** browser-service/scripts/construire.ts — bundle of the browser service (dist/main.mjs), run by the mounted Node inside each sandbox: Playwright stays outside (browser-service/node_modules, mounted next to it), licence texts of the bundled packages in dist/LICENCES-TIERS.txt. */
import { existsSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";

import { build } from "esbuild";
import type { Metafile } from "esbuild";

import { empreinteSources } from "@elpis/commun/empreinte";

import {
  dossierPaquet,
  licencesLivrees,
  lirePaquet,
  RACINE,
  verifierLicences,
} from "../../apps/core/scripts/construire.ts";
import type { PaquetLivre } from "../../apps/core/scripts/construire.ts";

const SERVICE = path.join(RACINE, "browser-service");
/** Entry point of the service. */
const ENTREE = path.join(SERVICE, "server.js");
/** Resolved at run time from browser-service/node_modules (mounted read-only in the sandbox with the bundle). */
const EXTERNES = ["playwright", "playwright-core"];
const FICHIERS_CONSTRUCTION = [
  "tsconfig.base.json",
  "browser-service/package.json",
  "browser-service/package-lock.json",
  "browser-service/tsconfig.json",
  "browser-service/scripts/construire.ts",
  "apps/core/scripts/construire.ts",
];
const FILET = "=".repeat(78);

export interface ConstructionService {
  sortie: string;
  empreinte: string;
  sources: string[];
  paquets: PaquetLivre[];
}

/** npm packages whose code is written in the bundle (bytes > 0), with their licence texts. */
export function paquetsDuBundle(meta: Metafile): PaquetLivre[] {
  const dossiers = new Set<string>();
  for (const sortie of Object.values(meta.outputs))
    for (const [entree, { bytesInOutput }] of Object.entries(sortie.inputs)) {
      const d = bytesInOutput > 0 ? dossierPaquet(entree) : null;
      if (d) dossiers.add(path.resolve(RACINE, d));
    }
  const paquets = new Map<string, PaquetLivre>();
  for (const d of dossiers) {
    const p = lirePaquet(d);
    paquets.set(`${p.nom}@${p.version}`, p);
  }
  return [...paquets.values()].sort((a, b) => (a.nom < b.nom ? -1 : a.nom > b.nom ? 1 : 0));
}

/** Repository files the bundle is made of (metafile inputs outside node_modules), plus the build files. */
export function sourcesDuService(meta: Metafile): string[] {
  const fichiers = new Set(FICHIERS_CONSTRUCTION);
  for (const entree of Object.keys(meta.inputs))
    if (!entree.includes("node_modules/") && existsSync(path.join(RACINE, entree))) fichiers.add(entree);
  return [...fichiers].sort();
}

function texteLicences(paquets: readonly PaquetLivre[]): string {
  const blocs = paquets.map(
    (p) => `${FILET}\n${p.nom} ${p.version} — ${p.licence}\n${FILET}\n\n${p.textes.join("\n\n")}\n`,
  );
  return (
    "npm packages bundled in the Elpis browser service (browser-service/dist): license text of each.\n" +
    "Playwright is not bundled: it stays in browser-service/node_modules with its own license files.\n" +
    "Generated by browser-service/scripts/construire.ts; do not edit by hand.\n\n" +
    blocs.join("\n")
  );
}

/** Builds next to `sortie`, then replaces it at once: a failed build leaves the previous bundle intact. */
export async function construireService(sortie: string): Promise<ConstructionService> {
  const provisoire = `${sortie}.construction-${process.pid}`;
  rmSync(provisoire, { recursive: true, force: true });
  try {
    const resultat = await build({
      absWorkingDir: RACINE,
      entryPoints: { main: ENTREE },
      outdir: provisoire,
      outExtension: { ".js": ".mjs" },
      bundle: true,
      platform: "node",
      target: "node24",
      format: "esm",
      charset: "utf8",
      external: EXTERNES,
      banner: {
        js: 'import { createRequire as __elpisRequire } from "node:module"; const require = __elpisRequire(import.meta.url);',
      },
      sourcemap: "linked",
      sourcesContent: false,
      metafile: true,
      logLevel: "warning",
    });
    const paquets = paquetsDuBundle(resultat.metafile);
    verifierLicences(paquets, licencesLivrees());
    writeFileSync(path.join(provisoire, "LICENCES-TIERS.txt"), texteLicences(paquets));
    const sources = sourcesDuService(resultat.metafile);
    const empreinte = empreinteSources(RACINE, sources);
    const version = (
      JSON.parse(readFileSync(path.join(SERVICE, "package.json"), "utf-8")) as { version: string }
    ).version;
    writeFileSync(
      path.join(provisoire, "construction.json"),
      JSON.stringify({ version, empreinte, sources }, null, 2) + "\n",
    );
    const ancien = `${sortie}.ancien-${process.pid}`;
    if (existsSync(sortie)) renameSync(sortie, ancien);
    try {
      renameSync(provisoire, sortie);
    } catch (e) {
      if (existsSync(ancien)) renameSync(ancien, sortie);
      throw e;
    }
    rmSync(ancien, { recursive: true, force: true });
    return { sortie, empreinte, sources, paquets };
  } catch (e) {
    rmSync(provisoire, { recursive: true, force: true });
    throw e;
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
  const argv = process.argv.slice(2);
  let sortie = path.join(SERVICE, "dist");
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === "--sortie" && argv[i + 1]) sortie = path.resolve(argv[(i += 1)] ?? "");
    else throw new Error("usage: construire.ts [--sortie DIRECTORY]");
  }
  const fait = await construireService(sortie);
  process.stdout.write(
    `browser service built in ${path.relative(RACINE, fait.sortie) || fait.sortie}: ` +
      `${fait.paquets.length} npm packages bundled, fingerprint ${fait.empreinte.slice(0, 12)}\n`,
  );
}
