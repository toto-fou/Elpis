export type Methode = "GET" | "POST" | "PUT" | "PATCH" | "DELETE";

export interface ContratRoute {
  readonly methode: Methode;
  /** Chemin à la Fastify (`:chat_id`), tel que le core le monte. */
  readonly chemin: string;
  readonly domaine: string;
  readonly corps?: z.ZodType;
  /** Réponse de succès (200, ou `statut`) ; `null` : 204 sans corps. */
  readonly reponse: z.ZodType | null;
  /** Code HTTP de succès quand ce n'est pas 200 (webhook : 202). */
  readonly statut?: number;
}

export function c(
  domaine: string,
  methode: Methode,
  chemin: string,
  reponse: z.ZodType | null,
  corps?: z.ZodType,
): ContratRoute {
  return corps === undefined
    ? { methode, chemin, domaine, reponse }
    : { methode, chemin, domaine, reponse, corps };
}

