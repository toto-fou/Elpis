export function motif(chemin: string): RegExp {
  const echappe = chemin
    .split("/")
    .map((s) => (s.startsWith(":") ? "[^/]+" : s.replace(/[.*+?^${}()|[\]\\]/gu, "\\$&")))
    .join("/");
  return new RegExp(`^${echappe}$`, "u");
}

const MOTIFS = CONTRATS_REST.map((r) => ({ r, re: motif(r.chemin), statique: !r.chemin.includes(":") }));

/** Contrat d'une requête concrète (chaîne de requête ignorée) ; un chemin fixe l'emporte sur un chemin paramétré. */
export function contratDe(methode: string, url: string): ContratRoute | undefined {
  const chemin = url.split("?")[0] ?? url;
  const candidats = MOTIFS.filter((m) => m.r.methode === methode && m.re.test(chemin));
  return (candidats.find((m) => m.statique) ?? candidats[0])?.r;
}
