/** packages/db/src/schema.ts — modèle déclaratif des tables et rendu de leur DDL par dialecte (port de shared_infra/db/_schema.py). */
import type { Base, Executeur } from "./base";
import type { Dialecte } from "./dialecte";
import { ErreurBase } from "./erreurs";
import { FTS_SQLITE, TABLES } from "./schema.gen";

export class ErreurSchema extends ErreurBase {
  override name = "ErreurSchema";
}

export type TypeCol = "id" | "int" | "real" | "text" | "text_ci";

export interface Col {
  name: string;
  type: TypeCol;
  null?: boolean;
  /** `null` = DEFAULT NULL explicite ; absent = pas de défaut. */
  default?: string | number | null;
  primary?: boolean;
  unique?: boolean;
  check?: string;
  types?: Partial<Record<Dialecte, TypeCol>>;
}

export interface Fk {
  cols: string[];
  table: string;
  refCols: string[];
  onDelete?: string;
}

export interface Index {
  name: string;
  cols: string[];
  unique?: boolean;
  where?: string;
}

export interface Table {
  name: string;
  cols: Col[];
  pk?: string[];
  unique?: string[][];
  fks?: Fk[];
  indexes?: Index[];
  only?: Dialecte[];
}

const TYPES_SQL: Readonly<Record<Dialecte, Record<"int" | "real" | "text", string>>> = {
  sqlite: { int: "INTEGER", real: "REAL", text: "TEXT" },
  postgres: { int: "BIGINT", real: "DOUBLE PRECISION", text: "TEXT" },
};

export function q(nom: string): string {
  return `"${nom.replaceAll('"', '""')}"`;
}

function litteral(v: string | number | null): string {
  if (v === null) return "NULL";
  if (typeof v === "number") return String(v);
  return `'${v.replaceAll("'", "''")}'`;
}

function typeCol(c: Col, d: Dialecte): string {
  const t = c.types?.[d] ?? c.type;
  return TYPES_SQL[d][t === "text_ci" ? "text" : (t as "int" | "real" | "text")];
}

export function colSql(c: Col, d: Dialecte): string {
  if (c.type === "id") {
    return d === "sqlite"
      ? `${q(c.name)} INTEGER PRIMARY KEY AUTOINCREMENT`
      : `${q(c.name)} BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY`;
  }
  const parts = [q(c.name), typeCol(c, d)];
  if (c.primary) parts.push("PRIMARY KEY");
  if (c.unique) parts.push("UNIQUE");
  if (c.null === false) parts.push("NOT NULL");
  if (c.default !== undefined) parts.push(`DEFAULT ${litteral(c.default)}`);
  if (c.check) parts.push(`CHECK (${c.check})`);
  return parts.join(" ");
}

export function createTableSql(t: Table, d: Dialecte): string {
  const lignes = t.cols.map((c) => colSql(c, d));
  if (t.pk?.length) lignes.push(`PRIMARY KEY (${t.pk.map(q).join(", ")})`);
  for (const u of t.unique ?? []) lignes.push(`UNIQUE (${u.map(q).join(", ")})`);
  for (const fk of t.fks ?? []) {
    const od = fk.onDelete ? ` ON DELETE ${fk.onDelete}` : "";
    lignes.push(
      `FOREIGN KEY (${fk.cols.map(q).join(", ")}) REFERENCES ${q(fk.table)}(${fk.refCols.map(q).join(", ")})${od}`,
    );
  }
  return `CREATE TABLE IF NOT EXISTS ${q(t.name)} (\n  ${lignes.join(",\n  ")}\n)`;
}

export function createIndexSql(t: Table, ix: Index, _d: Dialecte): string {
  const cols = ix.cols.map((part) => {
    const [nom, ...reste] = part.split(/\s+/u);
    return [q(nom ?? ""), ...reste].join(" ");
  });
  const where = ix.where ? ` WHERE ${ix.where}` : "";
  return `CREATE ${ix.unique ? "UNIQUE " : ""}INDEX IF NOT EXISTS ${q(ix.name)} ON ${q(t.name)} (${cols.join(", ")})${where}`;
}

/** Définition pour ALTER TABLE … ADD COLUMN : sans PRIMARY KEY ni UNIQUE, refusés par SQLite. */
export function addColumnSql(c: Col, d: Dialecte): string {
  const { primary: _p, unique: _u, ...simple } = c;
  return colSql(simple, d);
}

export async function tableNames(x: Executeur): Promise<string[]> {
  const sql =
    x.dialecte === "sqlite"
      ? "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name"
      : "SELECT table_name AS name FROM information_schema.tables WHERE table_schema = current_schema() " +
        "AND table_type = 'BASE TABLE' ORDER BY table_name";
  return (await x.all<{ name: string }>(sql)).map((r) => r.name);
}

export async function tableColumns(x: Executeur, table: string): Promise<string[]> {
  if (x.dialecte === "sqlite") {
    const lignes = await x.all<{ name: string }>(`PRAGMA table_info(${q(table)})`).catch(() => []);
    return lignes.map((r) => r.name);
  }
  const lignes = await x.all<{ name: string }>(
    "SELECT column_name AS name FROM information_schema.columns WHERE table_schema = current_schema() " +
      "AND table_name = ? ORDER BY ordinal_position",
    [table],
  );
  return lignes.map((r) => r.name);
}

export async function hasTable(x: Executeur, table: string): Promise<boolean> {
  if (x.dialecte === "sqlite") {
    return (
      (await x.get("SELECT 1 AS un FROM sqlite_master WHERE type='table' AND name=?", [table])) !== undefined
    );
  }
  return (await tableNames(x)).includes(table);
}

/** Ajoute à une table existante les colonnes du schéma qui lui manquent ; rend les ajoutées et celles qu'on ne peut pas ajouter. */
export async function addMissingColumns(
  x: Executeur,
  t: Table,
): Promise<{ ajoutees: string[]; impossibles: string[] }> {
  const presentes = new Set(await tableColumns(x, t.name));
  const r = { ajoutees: [] as string[], impossibles: [] as string[] };
  if (!presentes.size) return r;
  for (const c of t.cols) {
    if (presentes.has(c.name)) continue;
    if (c.type === "id" || c.primary || c.unique || (c.null === false && c.default === undefined)) {
      r.impossibles.push(`${t.name}.${c.name}`);
      continue;
    }
    await x.run(`ALTER TABLE ${q(t.name)} ADD COLUMN ${addColumnSql(c, x.dialecte)}`);
    r.ajoutees.push(`${t.name}.${c.name}`);
  }
  return r;
}

/** Crée les tables manquantes, leurs colonnes manquantes et leurs index (idempotent, comme `ensure_tables`). */
/** Crée les tables, colonnes et index manquants (`ensure_tables`) ; en PostgreSQL, un index ou une table déjà là n'est pas recréé : `IF NOT EXISTS` y verrouille la table jusqu'au COMMIT. */
export async function ensureTables(
  x: Executeur,
  noms?: readonly string[],
): Promise<{ ajoutees: string[]; impossibles: string[] }> {
  const tables = noms ? noms.map((n) => tableParNom(n)) : TABLES;
  const r = { ajoutees: [] as string[], impossibles: [] as string[] };
  const pg = x.dialecte === "postgres";
  const tablesLa = new Set(pg ? await tableNames(x) : []);
  const indexLa = new Set(
    pg
      ? (
          await x.all<{ n: string }>(
            "SELECT indexname AS n FROM pg_indexes WHERE schemaname = current_schema()",
          )
        ).map((i) => i.n)
      : [],
  );
  for (const t of tables) {
    if (t.only && !t.only.includes(x.dialecte)) continue;
    if (!tablesLa.has(t.name)) await x.run(createTableSql(t, x.dialecte));
    const c = await addMissingColumns(x, t);
    r.ajoutees.push(...c.ajoutees);
    r.impossibles.push(...c.impossibles);
    for (const ix of t.indexes ?? [])
      if (!indexLa.has(ix.name)) await x.run(createIndexSql(t, ix, x.dialecte));
  }
  return r;
}

export function tableParNom(nom: string): Table {
  const t = TABLES.find((x) => x.name === nom);
  if (!t) throw new ErreurSchema(`table inconnue du schéma : ${nom}`);
  return t;
}

const PONCTUATION_FTS = "!\"#$%&'()*+,-./:;<=>?@[\\]^_`{|}~«»‘’“”…–—·•";

export function pgFtsDocument(col: string): string {
  return `translate(${col}, '${PONCTUATION_FTS.replaceAll("'", "''")}', '${" ".repeat(Array.from(PONCTUATION_FTS).length)}')`;
}

export interface RapportFts {
  fts: boolean;
  unaccent: boolean;
  avertissements: string[];
}

function message(e: unknown): string {
  return e instanceof Error ? e.message : String(e);
}

/** Plein texte de `session_messages` (FTS5 en SQLite, tsvector + unaccent en PostgreSQL) ; les dégradations sont rendues, à journaliser. */
export async function ensureFts(base: Base): Promise<RapportFts> {
  const r: RapportFts = { fts: false, unaccent: base.dialecte === "sqlite", avertissements: [] };
  try {
    await base.transaction(async (x) => {
      if (x.dialecte === "sqlite") {
        for (const sql of FTS_SQLITE) await x.run(sql);
        return;
      }
      r.unaccent = await base
        .transaction(async (y) => {
          if (!(await y.get("SELECT 1 AS un FROM pg_extension WHERE extname = 'unaccent'"))) {
            await y.run("CREATE EXTENSION IF NOT EXISTS unaccent SCHEMA public");
          }
        })
        .then(() => true)
        .catch((e: unknown) => {
          r.avertissements.push(
            `extension unaccent indisponible (${message(e)}) : recherche sensible aux accents`,
          );
          return false;
        });
      const conf = await x.get(
        "SELECT 1 AS un FROM pg_ts_config WHERE cfgname = 'elpis_simple' AND cfgnamespace = current_schema()::regnamespace",
      );
      if (!conf) {
        await x.run("CREATE TEXT SEARCH CONFIGURATION elpis_simple (COPY = pg_catalog.simple)");
        if (r.unaccent) {
          await x.run(
            "ALTER TEXT SEARCH CONFIGURATION elpis_simple ALTER MAPPING FOR word, numword, hword, hword_part, " +
              "numhword, hword_numpart WITH public.unaccent, simple",
          );
        }
      }
      if (!(await tableColumns(x, "session_messages")).includes("content_tsv")) {
        await x.run(
          "ALTER TABLE session_messages ADD COLUMN content_tsv tsvector GENERATED ALWAYS AS " +
            `(to_tsvector('elpis_simple', ${pgFtsDocument("content")})) STORED`,
        );
      }
      if (
        !(await x.get(
          "SELECT 1 AS un FROM pg_indexes WHERE schemaname = current_schema() AND indexname = 'idx_sm_fts'",
        ))
      ) {
        await x.run("CREATE INDEX IF NOT EXISTS idx_sm_fts ON session_messages USING GIN (content_tsv)");
      }
    });
    r.fts = true;
  } catch (e) {
    r.avertissements.push(`plein texte indisponible (${message(e)}) : recherche d'historique en LIKE`);
  }
  return r;
}

export interface RapportSchema extends RapportFts {
  ajoutees: string[];
  impossibles: string[];
}

/** Schéma complet (`create_all`) : tables, colonnes, index, verrou d'écriture des serveurs, plein texte. */
export async function createAll(base: Base): Promise<RapportSchema> {
  const r = await base.transaction(async (x) => {
    const c = await ensureTables(x);
    if (x.dialecte !== "sqlite")
      await x.run("INSERT INTO elpis_locks(name) VALUES ('write') ON CONFLICT DO NOTHING");
    return c;
  });
  return { ...(await ensureFts(base)), ...r };
}

/** Base vierge : aucune table, hormis `elpis_locks` que le verrou d'écriture pose avant ce test. */
export async function isFresh(x: Executeur): Promise<boolean> {
  return (await tableNames(x)).every((n) => n === "elpis_locks");
}
