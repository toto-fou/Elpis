/** packages/db/test/contrat.test.ts — même contrat sur SQLite et PostgreSQL : exécution, executemany, transactions imbriquées, erreurs. */
import { afterAll, beforeAll, describe, expect, it } from "vitest";

import { setTimeout as attendre } from "node:timers/promises";

import { ErreurPython, FlottantPy } from "@elpis/commun";

import { ErreurIntegrite, ErreurProgrammation, estTableAbsente } from "../src/index";
import { ouvrirBaseDeTest, PG_DE_TEST } from "../src/test";
import type { BaseDeTest } from "../src/test";

const MOTEURS = PG_DE_TEST ? (["sqlite", "postgres"] as const) : (["sqlite"] as const);

describe.each(MOTEURS)("%s", (moteur) => {
  let t: BaseDeTest;

  beforeAll(async () => {
    t = ouvrirBaseDeTest(moteur);
    const id =
      moteur === "sqlite"
        ? "INTEGER PRIMARY KEY AUTOINCREMENT"
        : "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY";
    await t.base.exec(`CREATE TABLE k (id ${id}, nom TEXT UNIQUE NOT NULL, n BIGINT DEFAULT 0)`);
  });

  afterAll(async () => t.fermer());

  it("insertId, get, all, run", async () => {
    const id = await t.base.insertId("INSERT INTO k(nom) VALUES (?)", ["un"]);
    expect(await t.base.get("SELECT nom, n FROM k WHERE id = ?", [id])).toEqual({ nom: "un", n: 0 });
    expect((await t.base.run("UPDATE k SET n = n + ? WHERE nom = ?", [2, "un"])).changes).toBe(1);
    expect(await t.base.all("SELECT nom FROM k WHERE nom LIKE ?", ["u%"])).toEqual([{ nom: "un" }]);
  });

  it("runMany est atomique", async () => {
    expect((await t.base.runMany("INSERT INTO k(nom) VALUES (?)", [["a"], ["b"], ["c"]])).changes).toBe(3);
    await expect(t.base.runMany("INSERT INTO k(nom) VALUES (?)", [["d"], ["a"]])).rejects.toBeInstanceOf(
      ErreurIntegrite,
    );
    expect(await t.base.get("SELECT COUNT(*) AS n FROM k WHERE nom = 'd'")).toEqual({ n: 0 });
  });

  it("ecriture() imbriquée dans une transaction, point de sauvegarde annulé seul", async () => {
    await t.base.transaction(async () => {
      await t.base.run("INSERT INTO k(nom) VALUES ('ext')");
      await t.base
        .ecriture(async (tx) => {
          await tx.run("INSERT INTO k(nom) VALUES ('int')");
          throw new Error("annulé");
        })
        .catch(() => undefined);
    });
    expect(await t.base.all("SELECT nom FROM k WHERE nom IN ('ext', 'int') ORDER BY nom")).toEqual([
      { nom: "ext" },
    ]);
  });

  it("lignes en tableaux, colonne en double : la première l'emporte", async () => {
    expect(await t.base.valeurs("SELECT 1 AS a, 'deux' AS b")).toEqual([[1, "deux"]]);
    expect(await t.base.get("SELECT 1 AS a, 2 AS a")).toEqual({ a: 1 });
  });

  it("refuse les instructions de transaction brutes", async () => {
    await expect(t.base.run("BEGIN")).rejects.toBeInstanceOf(ErreurProgrammation);
    await expect(t.base.exec("SELECT 1; COMMIT")).rejects.toBeInstanceOf(ErreurProgrammation);
  });

  it("insertId : RETURNING explicite et WITH … INSERT", async () => {
    const a = await t.base.insertId("INSERT INTO k(nom) VALUES ('r1') RETURNING id");
    const b = await t.base.insertId("WITH v(x) AS (SELECT 'r2') INSERT INTO k(nom) SELECT x FROM v");
    expect(b).toBe(a + 1);
    expect(await t.base.runMany("INSERT INTO k(nom) VALUES (?)", [])).toEqual({
      changes: 0,
      lastInsertRowid: null,
    });
  });

  it("transactions imbriquées en parallèle : sérialisées, chacune annulée seule, erreur d'origine gardée", async () => {
    let erreur: unknown;
    await t.base.transaction(async () => {
      const ok = t.base.transaction(async (x) => {
        await x.run("INSERT INTO k(nom) VALUES ('para-ok')");
        await attendre(20);
      });
      const ko = t.base.transaction(async (x) => {
        await x.run("INSERT INTO k(nom) VALUES ('para-ko')");
        throw new Error("échec B");
      });
      erreur = await ko.catch((e: unknown) => e);
      await ok;
    });
    expect((erreur as Error).message).toBe("échec B");
    expect(await t.base.all("SELECT nom FROM k WHERE nom LIKE 'para-%' ORDER BY nom")).toEqual([
      { nom: "para-ok" },
    ]);
  });

  it("une imbriquée non attendue termine avant que la parente ne valide", async () => {
    await t.base.transaction(async () => {
      void t.base.transaction(async (x) => {
        await attendre(30);
        await x.run("INSERT INTO k(nom) VALUES ('tardive')");
      });
    });
    expect(await t.base.get("SELECT COUNT(*) AS n FROM k WHERE nom = 'tardive'")).toEqual({ n: 1 });
  });

  it("demi-paire isolée : ValueError comme sqlite3, ProgrammingError comme psycopg ; rien d'écrit", async () => {
    const essai = t.base.run("INSERT INTO k(nom) VALUES (?)", [`é\u{1f600}x${String.fromCharCode(0xdc00)}`]);
    await expect(essai).rejects.toThrow(moteur === "sqlite" ? ErreurPython : ErreurProgrammation);
    await expect(essai).rejects.toThrow(
      "'utf-8' codec can't encode character '\\udc00' in position 3: surrogates not allowed",
    );
    expect(await t.base.get("SELECT COUNT(*) AS n FROM k WHERE nom LIKE ?", ["é%"])).toEqual({ n: 0 });
    await t.base.run("INSERT INTO k(nom) VALUES (?)", ["é\u{1f600}"]);
  });

  it("liaison comme sqlite3 : entier en INTEGER, FlottantPy en REAL, liste ou dict refusés", async () => {
    if (moteur === "sqlite") {
      expect(
        await t.base.get("SELECT typeof(?) AS a, typeof(?) AS b, typeof(?) AS c", [
          5,
          new FlottantPy(1) as never,
          2.5,
        ]),
      ).toEqual({ a: "integer", b: "real", c: "real" });
      await t.base.exec("CREATE TABLE IF NOT EXISTS libre (t TEXT)");
      await t.base.run("INSERT INTO libre VALUES (?), (?)", [5, new FlottantPy(5) as never]);
      expect(await t.base.all("SELECT t FROM libre")).toEqual([{ t: "5" }, { t: "5.0" }]);
    }
    await expect(t.base.run("SELECT ?", [[1] as never])).rejects.toThrow(ErreurProgrammation);
    await expect(t.base.run("SELECT ?", [{ a: 1 } as never])).rejects.toThrow(ErreurProgrammation);
  });

  it("table absente reconnue", async () => {
    expect(estTableAbsente(await t.base.all("SELECT * FROM nulle_part").catch((e: unknown) => e))).toBe(true);
  });
});
